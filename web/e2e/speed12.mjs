import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome-stable', args: ['--no-sandbox'] })
const page = await browser.newPage()
await page.goto('http://127.0.0.1:47123/')
const cores = await page.evaluate(() => navigator.hardwareConcurrency)
const t0 = Date.now()
await page.setInputFiles('input[type=file] >> nth=0', '/tmp/mosaic_12mp.png')
await page.getByText(/compressed in/).waitFor({ timeout: 900_000 })
const t1 = Date.now()
const text = await page.locator('p:has-text("compressed in")').first().innerText()
console.log(`cores ${cores}; compressed after ${((t1 - t0) / 1000).toFixed(1)} s: ${text}`)
await page.getByText('Bit-exact round trip verified').waitFor({ timeout: 900_000 })
console.log(`verified after ${((Date.now() - t0) / 1000).toFixed(1)} s`)
await browser.close()
