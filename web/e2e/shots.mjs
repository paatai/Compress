import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome-stable', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 1 })
await page.goto('http://127.0.0.1:47124/')
await page.setInputFiles('input[type=file] >> nth=0', '../bench/data/dev/graphics/graphics_0204773781.png')
await page.getByText('Bit-exact round trip verified').waitFor({ timeout: 120000 })
await page.getByRole('button', { name: /Compare with WebP and JPEG XL/ }).click()
await page.getByText(/lossless, effort/).waitFor({ timeout: 300000 })
await page.locator('div[data-slot=card]').first().screenshot({ path: '/tmp/shot-card.png' })
await page.locator('#benchmark').screenshot({ path: '/tmp/shot-bench.png' })
const m = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
await m.goto('http://127.0.0.1:47124/')
await m.setInputFiles('input[type=file] >> nth=0', '../bench/data/dev/graphics/graphics_0204773781.png')
await m.getByText('Bit-exact round trip verified').waitFor({ timeout: 120000 })
await m.screenshot({ path: '/tmp/shot-mobile.png' })
await m.locator('div[data-slot=card]').first().screenshot({ path: '/tmp/shot-mobile-card.png' })
await browser.close()
